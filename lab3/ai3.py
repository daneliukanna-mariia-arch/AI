import os
from dotenv import load_dotenv
from google import genai

# 1. Ініціалізація клієнта та налаштування моделі
load_dotenv()
api_key = os.getenv("GEMINI_API_KEY")

client = genai.Client(api_key=api_key)
MODEL = "gemini-3.5-flash"


def run_laboratory_work_3():
    print("=" * 60)
    print("ЛАБОРАТОРНА РОБОТА № 3: Основи Prompt Engineering")
    print("=" * 60)

    # ЗАВДАННЯ 1. Взаємодія з великою мовною моделлю (5 типів запитів)

    print("\n" + "=" * 40)
    print("ЗАВДАННЯ 1: 5 ТИПІВ ЗАПИТІВ")
    print("=" * 40)

    # 1. Пояснення
    prompt_1 = """
    Поясни, що таке об'єктно-орієнтоване програмування (ООП). 
    Опиши основні принципи його роботи (інкапсуляція, успадкування, поліморфізм, абстракція) та наведи приклади використання.
    """
    res1 = client.models.generate_content(model=MODEL, contents=prompt_1)
    print("\n--- 1.1. ПОЯСНЕННЯ ---")
    print(res1.text)

    # 2. Генерація тексту
    prompt_2 = """
    Напиши невеликий текст на тему "Практична користь об'єктно-орієнтованого програмування (ООП) у розробці сучасних програм". 
    Розкрий, як ООП допомагає програмістам структурувати код, повторно використовувати його та полегшувати підтримку великих проєктів.
    Обсяг тексту — приблизно 100 слів.
    """
    res2 = client.models.generate_content(model=MODEL, contents=prompt_2)
    print("\n--- 1.2. ГЕНЕРАЦІЯ ТЕКСТУ ---")
    print(res2.text)

    # 3. Переклад
    prompt_3 = """
    Переклади українською мовою такий текст:

    "Object-oriented programming is a fundamental paradigm in software development. It structures code using classes and objects, making projects easier to maintain, scale, and reuse."
    """
    res3 = client.models.generate_content(model=MODEL, contents=prompt_3)
    print("\n--- 1.3. ПЕРЕКЛАД ---")
    print(res3.text)

    # 4. Узагальнення / Скорочення
    prompt_4 = """
    Скороти та узагальни наведений текст, залишивши тільки основні думки:

    "Об'єктно-орієнтоване програмування (ООП) широко застосовується в розробці сучасних програмних систем. У веб-розробці ООП дозволяє легко розділяти логіку сервера на окремі модулі та сервіси. У створенні комп'ютерних ігор об'єкти виступають ігровими персонажами, предметами та елементами оточення, що суттєво спрощує керування їхньою поведінкою. У мобільній розробці ООП лежить в основі побудови графічного інтерфейсу та обробки подій користувача. Також принципи ООП активно застосовуються у банківському програмному забезпеченні, корпоративних системах та розробці баз даних."
    """
    res4 = client.models.generate_content(model=MODEL, contents=prompt_4)
    print("\n--- 1.4. СКОРОЧЕННЯ ТА УЗАГАЛЬНЕННЯ ---")
    print(res4.text)

    # 5. Генерація списку
    prompt_5 = """
    Сформуй список із 5 переваг використання об'єктно-орієнтованого програмування (ООП) у розробці ПЗ. 
    Для кожної переваги додай коротке пояснення.
    """
    res5 = client.models.generate_content(model=MODEL, contents=prompt_5)
    print("\n--- 1.5. ГЕНЕРАЦІЯ СПИСКУ ---")
    print(res5.text)


    # ЗАВДАННЯ 2. Порівняння способів формування prompt
  
    print("\n" + "=" * 40)
    print("ЗАВДАННЯ 2: ZERO-SHOT VS FEW-SHOT")
    print("=" * 40)

    # 1. Zero-shot prompt
    prompt_zero_shot = """
    Поясни, як об'єктно-орієнтоване програмування (ООП) використовується у розробці програм. 
    Наведи 4 приклади його застосування в реальних проєктах та коротко опиши кожен із них. 
    Використовуй прості та зрозумілі слова.
    """
    res_zero = client.models.generate_content(
        model=MODEL, contents=prompt_zero_shot
    )
    print("\n--- 2.1. ZERO-SHOT PROMPT ---")
    print(res_zero.text)

    # 2. Few-shot prompt
    prompt_few_shot = """
    Нижче наведено приклади опису принципів об'єктно-орієнтованого програмування (ООП).

    Приклад 1.
    Принцип: Інкапсуляція.
    Опис: Об'єднання даних і методів у класі з обмеженням прямого доступу до них ззовні.

    Приклад 2.
    Принцип: Успадкування.
    Опис: Створення нового класу на основі існуючого з можливістю перевизначення методів.

    Приклад 3.
    Принцип: Поліморфізм.
    Опис: Здатність об'єктів різних класів реалізовувати однаковий інтерфейс по-різному.

    Тепер виконай завдання за аналогічним принципом.

    Поясни, як об'єктно-орієнтоване програмування застосовується у реальних проєктах. 
    Наведи 4 приклади його використання у розробці програмного забезпечення за вказаною структурою.
    """
    res_few = client.models.generate_content(
        model=MODEL, contents=prompt_few_shot
    )
    print("\n--- 2.2. FEW-SHOT PROMPT ---")
    print(res_few.text)


    # ЗАВДАННЯ 3. Удосконалення prompt

    print("\n" + "=" * 40)
    print("ЗАВДАННЯ 3: УДОСКОНАЛЕННЯ PROMPT")
    print("=" * 40)

    # 1. Простий prompt
    prompt_initial = """
    Розкажи про вплив об'єктно-орієнтованого програмування (ООП) на майбутнє розробки ПЗ.
    """
    res_initial = client.models.generate_content(
        model=MODEL, contents=prompt_initial
    )
    print("\n--- 3.1. ПОЧАТКОВИЙ PROMPT ---")
    print(res_initial.text)

    # 2. Вдосконалений prompt
    prompt_improved = """
    Ти — фахівець із архітектури програмного забезпечення та навчальних технологій. 
    Поясни, як об'єктно-орієнтоване програмування (ООП) впливає на майбутнє розробки ПЗ та які зміни воно приносить у сучасну IT-індустрію.

    Зверни увагу на такі аспекти:
    - Які підходи в розробці змінюються під впливом ООП;
    - Які нові можливості відкриваються для програмістів;
    - Які навички будуть важливими в майбутньому.

    Пояснення має бути призначене для студентів. 
    Використовуй прості та зрозумілі слова, наводь конкретні приклади.

    Обсяг відповіді — приблизно 200 слів. 
    Оформи відповідь у вигляді короткого вступу та нумерованого списку основних змін.
    """
    res_improved = client.models.generate_content(
        model=MODEL, contents=prompt_improved
    )
    print("\n--- 3.2. ВДОСКОНАЛЕНИЙ PROMPT ---")
    print(res_improved.text)

   
    # ЗАВДАННЯ 4. Використання системної ролі
    
    print("\n" + "=" * 40)
    print("ЗАВДАННЯ 4: РОЛЬОВИЙ PROMPTING (SYSTEM ROLES)")
    print("=" * 40)

    # 1. Роль Викладача
    prompt_teacher = """
    Ти — досвідчений викладач із програмування та архітектури ПЗ. 
    Поясни, як працює об'єктно-орієнтоване програмування (ООП) і на чому ґрунтується його здатність моделювати складні системи.
    """
    res_teacher = client.models.generate_content(
        model=MODEL, contents=prompt_teacher
    )
    print("\n--- 4.1. РОЛЬ ВИКЛАДАЧА ---")
    print(res_teacher.text)

    # 2. Роль Науковця
    prompt_scientist = """
    Ти — науковець у галузі Computer Science, який досліджує парадигми програмування. 
    Поясни, як працює об'єктно-орієнтоване програмування (ООП) і на чому ґрунтується його здатність моделювати складні системи.
    """
    res_scientist = client.models.generate_content(
        model=MODEL, contents=prompt_scientist
    )
    print("\n--- 4.2. РОЛЬ НАУКОВЦЯ ---")
    print(res_scientist.text)

    # 3. Роль Програміста
    prompt_programmer = """
    Ти — Senior Python Developer та софтверний архітектор із 10-річним досвідом. 
    Поясни, як об'єктно-орієнтоване програмування (ООП) працює в реальних виробничих (production) проєктах та як воно допомагає моделювати складні системи.

    Зосередься на практичному застосуванні:
    - Покажи приклад чистого Python-коду з використанням класів, dunder-методів, паттернів або декораторів (наприклад, @dataclass чи @abstractmethod);
    - Поясни, як ООП допомагає писати тестівний (testable) та масштабований код на практиці;
    - Вкажи на типові помилки розробників при використанні ООП (наприклад, переускладнення ієрархій або порушення SOLID) та як їх уникати.

    Викладай матеріал лаконічно, прагматично, з точки зору реального написання та підтримки коду.
    """
    res_programmer = client.models.generate_content(
        model=MODEL, contents=prompt_programmer
    )
    print("\n--- 4.3. РОЛЬ ПРОГРАМІСТА ---")
    print(res_programmer.text)

    print("\n" + "=" * 60)
    print("УСІ ЗАВДАННЯ УСПІШНО ВИКОНАНО!")
    print("=" * 60)


if __name__ == "__main__":
    run_laboratory_work_3()
